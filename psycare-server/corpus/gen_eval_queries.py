def check_corpus():
    """把语料读成 (section 全集, 全文) 供校验用。"""
    sections, full = [], []
    for line in open(CORPUS, encoding="utf-8"):
        s = line.strip()
        if not s:
            continue
        o = json.loads(s)
        sections.append(o.get("section", ""))
        full.append(o.get("content", ""))
    return sections, "\n".join(full)


def main():
    sections, full_text = check_corpus()
    sec_join = "\n".join(sections)

    print("校验评测集与语料的对应关系")
    print("-" * 68)
    bad = 0
    seen_q = set()

    # ---- 库内 ----
    rows_in = []
    for q, sec_frag, kws, note in IN_QUERIES:
        if q in seen_q:
            print(f"  ✗ query 重复：{q}")
            bad += 1
        seen_q.add(q)

        if sec_frag not in sec_join:
            print(f"  ✗ section 片段在语料中找不到：{sec_frag!r}  （query: {q}）")
            bad += 1

        missing = [k for k in kws if k not in full_text]
        if missing:
            print(f"  ✗ 关键词在语料全文中找不到：{missing}  （query: {q}）")
            bad += 1

        rows_in.append({
            "query": q,
            "expect_sections": [sec_frag],
            "expect_keywords": kws,
            "note": note,
        })

    # ---- 库外 ----
    rows_out = []
    for q, dom in OUT_QUERIES:
        if q in seen_q:
            print(f"  ✗ query 重复：{q}")
            bad += 1
        seen_q.add(q)
        rows_out.append({"query": q, "domain": dom,
                         "note": "库外：" + dom + "，期望检索为空"})

    # 库内/库外交叉重复检查（写反了会同时污染两个指标）
    in_q = {r["query"] for r in rows_in}
    out_q = {r["query"] for r in rows_out}
    cross = in_q & out_q
    if cross:
        for q in cross:
            print(f"  ✗ 库内/库外重复：{q}")
            bad += 1

    if bad:
        print(f"\n❌ 有 {bad} 处问题，未写出文件")
        return 1

    with open(IN_OUT, "w", encoding="utf-8", newline="\n") as f:
        for r in rows_in:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    with open(OUT_OUT, "w", encoding="utf-8", newline="\n") as f:
        for r in rows_out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"  ✓ 库内 {len(rows_in)} 条、库外 {len(rows_out)} 条，无重复、无悬空引用")
    print()
    print(f"已写出：\n  {IN_OUT}\n  {OUT_OUT}")

    # 分布报告
    from collections import Counter
    c = Counter()
    for r in rows_in:
        c[r["expect_sections"][0].split("/")[0].strip()] += 1
    print("\n库内 query 按章节分布：")
    for k, v in c.items():
        print(f"  {v:>2}  {k}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
