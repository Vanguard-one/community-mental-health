     不是「机器人头」。机器人图标在 20px 下细节全丢，只剩一个圆角方块。

  <h3>为什么做成组件而不是两处各写一份 svg</h3>
  同一个符号要在两个尺寸（侧栏 20px、顶部导航 22px）下出现两次。
  各写一份的后果是「改了一处忘了另一处」—— 这正是本项目 SideRail 抽组件
